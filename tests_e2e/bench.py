"""Measured performance on this machine. Run:  python tests_e2e/bench.py [--out docs/benchmarks.json]

Everything here is real: a real service process, real Chromium, real documents generated by tests_py/fixtures.py. Numbers are wall-clock
milliseconds measured inside the page (so they include the HTTP round trip on localhost) unless a line says otherwise. The machine and the
browser are recorded with the results, because they are the context without which the numbers mean nothing.
"""
from __future__ import annotations

import argparse
import json
import os
import platform
import shutil
import statistics
import sys
import tempfile
import time
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
from harness import APP, Service, fx  # noqa: E402


def pct(values, p):
    v = sorted(values)
    return v[min(len(v) - 1, int(round((len(v) - 1) * p)))]


def summary(values):
    return {"n": len(values), "p50": round(pct(values, 0.5), 1), "p95": round(pct(values, 0.95), 1), "max": round(max(values), 1)}


def rss_mb(pid: int) -> float:
    try:
        for line in Path(f"/proc/{pid}/status").read_text().splitlines():
            if line.startswith("VmRSS"):
                return round(int(line.split()[1]) / 1024, 1)
    except OSError:
        pass
    return -1.0


def machine() -> dict:
    cpu = "unknown"
    try:
        cpu = next(l.split(":", 1)[1].strip() for l in Path("/proc/cpuinfo").read_text().splitlines() if l.startswith("model name"))
    except Exception:
        cpu = platform.processor() or platform.machine()
    mem = "unknown"
    try:
        mem = f"{int(next(l for l in Path('/proc/meminfo').read_text().splitlines() if l.startswith('MemTotal')).split()[1]) // 1024} MB"
    except Exception:
        pass
    return {"cpu": cpu, "cores": os.cpu_count(), "memory": mem, "os": platform.platform(), "python": platform.python_version()}


FETCH = """async ([method, url, body]) => {
  const t0 = performance.now();
  const r = await fetch(url, { method, headers: { 'X-SLAI-Reader': '1', 'Content-Type': 'application/json' }, body: body ? JSON.stringify(body) : undefined });
  const text = await r.text(); const ms = performance.now() - t0;
  let json = null; try { json = JSON.parse(text); } catch (e) {}
  return { status: r.status, ms, bytes: text.length, json };
}"""


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default=str(APP / "docs" / "benchmarks.json"))
    ap.add_argument("--pages", type=int, default=400)
    ap.add_argument("--paragraphs", type=int, default=17000)
    ap.add_argument("--marks", type=int, default=2000)
    args = ap.parse_args()

    from playwright.sync_api import sync_playwright
    tmp = Path(tempfile.mkdtemp(prefix="reader-bench-"))
    docs = tmp / "docs"; docs.mkdir()
    svc = Service(tmp); svc.start()
    results: dict = {"machine": machine(), "when": time.strftime("%Y-%m-%d %H:%M:%S"), "results": {}}
    R = results["results"]
    try:
        t = time.time(); big = fx.make_big_pdf(docs / "big.pdf", args.pages); R["fixture_big_pdf"] = {"pages": args.pages, "bytes": big.stat().st_size, "built_s": round(time.time() - t, 1)}
        t = time.time(); long_sldc = fx.make_sldc(docs / "long.sldc", paragraphs=args.paragraphs, with_table=False, with_figure=False); R["fixture_long_sldc"] = {"paragraphs": args.paragraphs, "bytes": long_sldc.stat().st_size, "built_s": round(time.time() - t, 1)}

        with sync_playwright() as pw:
            browser = pw.chromium.launch()
            R["browser"] = browser.version
            ctx = browser.new_context(viewport={"width": 1366, "height": 860})
            page = ctx.new_page()
            page.goto(svc.url)
            page.wait_for_selector("input[aria-label='Full path of a file to open']")
            call = lambda method, url, body=None: page.evaluate(FETCH, [method, url, body])  # noqa: E731

            # ------------------------------------------------------------------ big PDF, server side
            rss0 = rss_mb(svc.proc.pid)
            r = call("POST", "/api/open", {"path": str(big)})
            sid = r["json"]["data"]["sid"] if "data" in (r["json"] or {}) else r["json"]["sid"]
            R["pdf_open"] = {"pages": args.pages, "ms": round(r["ms"], 1), "payload_kb": round(r["bytes"] / 1024, 1)}
            img, txt = [], []
            for n in list(range(0, args.pages, max(1, args.pages // 40)))[:40]:
                img.append(call("GET", f"/api/doc/{sid}/page/{n}/image?scale=1.5&fmt=jpeg")["ms"])
                txt.append(call("GET", f"/api/doc/{sid}/page/{n}/text")["ms"])
            R["pdf_page_image_ms"] = summary(img); R["pdf_page_text_ms"] = summary(txt)
            s1 = call("GET", f"/api/doc/{sid}/search?q=needle7&limit=200")
            s2 = call("GET", f"/api/doc/{sid}/search?q=needle7&limit=200")
            d = (s1["json"].get("data") or s1["json"])
            R["pdf_search"] = {"query": "needle7", "first_call_ms": round(s1["ms"], 1), "second_call_ms": round(s2["ms"], 1), "hits": d.get("total"), "index": d.get("index")}
            R["server_rss_mb"] = {"before_open": rss0, "after_open_and_render": rss_mb(svc.proc.pid)}

            # ------------------------------------------------------------------ many annotations on the PDF
            created = []
            batch = []
            per_page = max(1, args.marks // args.pages)
            for n in range(args.pages):
                for k in range(per_page):
                    batch.append({"kind": "highlight", "anchor": {"kind": "pdf-text", "segments": [{"page": n, "start": 10 + k * 30, "end": 30 + k * 30}]}, "style": {"color": "#facc15"}})
            t0 = time.perf_counter()
            for i in range(0, len(batch), 200):
                rr = call("POST", f"/api/doc/{sid}/annotations", {"annotations": batch[i:i + 200], "label": "bulk"})
                if rr["status"] != 200:
                    raise RuntimeError(rr)
                created += rr["json"].get("data", rr["json"])["created"]
            R["annotations_bulk_create"] = {"count": len(created), "total_s": round(time.perf_counter() - t0, 2), "per_item_ms": round((time.perf_counter() - t0) * 1000 / len(created), 2)}
            lst = call("GET", f"/api/doc/{sid}/annotations")
            R["annotations_list"] = {"count": len(created), "ms": round(lst["ms"], 1), "payload_kb": round(lst["bytes"] / 1024, 1)}
            single = []
            for k in range(60):
                rr = call("POST", f"/api/doc/{sid}/annotations", {"kind": "highlight", "anchor": {"kind": "pdf-text", "segments": [{"page": 3, "start": 500 + k * 3, "end": 502 + k * 3}]}, "style": {"color": "#86efac"}})
                single.append(rr["ms"])
            R["annotation_single_create_ms (each is an fsync'd SQLite commit)"] = summary(single)
            marks = [call("GET", f"/api/doc/{sid}/page/{n}/marks")["ms"] for n in range(0, 40)]
            R["page_marks_ms"] = summary(marks)
            call("DELETE", f"/api/doc/{sid}")

            # ------------------------------------------------------------------ the browser, big PDF
            page.fill("input[aria-label='Full path of a file to open']", str(big))
            t0 = time.perf_counter()
            page.click("text=Open path")
            page.wait_for_selector(".status [role=status]:not(:empty)", timeout=60000)
            page.wait_for_selector(".pagehost[data-page='0'] img.page[src]", state="attached")
            R["browser_open_big_pdf_to_first_page_ms"] = round((time.perf_counter() - t0) * 1000)
            sweep = page.evaluate("""async () => {
              const v = document.querySelector('#view'); const frames = []; let last = performance.now();
              const raf = () => new Promise((res) => requestAnimationFrame(res));
              const total = v.scrollHeight - v.clientHeight; const step = v.clientHeight * 0.8; let maxDom = 0, maxImgs = 0;
              const t0 = performance.now();
              for (let y = 0; y < total; y += step) {
                v.scrollTop = y; await raf(); const now = performance.now(); frames.push(now - last); last = now;
                maxDom = Math.max(maxDom, document.getElementsByTagName('*').length);
                maxImgs = Math.max(maxImgs, document.querySelectorAll('img.page[src]').length);
                if (frames.length % 40 === 0) await new Promise((r) => setTimeout(r, 30));
              }
              const mem = performance.memory ? Math.round(performance.memory.usedJSHeapSize / 1048576) : null;
              return { steps: frames.length, wall_ms: Math.round(performance.now() - t0), frames, maxDom, maxImgs, heapMB: mem };
            }""")
            fr = sweep.pop("frames")
            R["browser_scroll_through_whole_pdf"] = {**sweep, "frame_ms": summary(fr), "frames_over_50ms": sum(1 for f in fr if f > 50)}
            R["server_rss_mb"]["after_full_scroll"] = rss_mb(svc.proc.pid)
            page.screenshot(path=str(APP / "docs" / "screenshots" / "P1_big_pdf_with_marks.png"))

            # ------------------------------------------------------------------ long text document
            page.goto(svc.url)
            page.wait_for_selector("input[aria-label='Full path of a file to open']")
            page.fill("input[aria-label='Full path of a file to open']", str(long_sldc))
            t0 = time.perf_counter()
            page.click("text=Open path")
            page.wait_for_selector("#view .b .txt", timeout=120000)
            R["browser_open_long_sldc_to_first_text_ms"] = round((time.perf_counter() - t0) * 1000)
            flow = page.evaluate("""async () => {
              const v = document.querySelector('#view'); const raf = () => new Promise((res) => requestAnimationFrame(res)); let maxBlocks = 0, maxDom = 0; const frames = []; let last = performance.now();
              const t0 = performance.now();
              for (let i = 0; i < 400; i++) { v.scrollTop += v.clientHeight * 3; await raf(); const now = performance.now(); frames.push(now - last); last = now;
                maxBlocks = Math.max(maxBlocks, document.querySelectorAll('#view .b').length); maxDom = Math.max(maxDom, document.getElementsByTagName('*').length);
                if (i % 25 === 0) await new Promise((r) => setTimeout(r, 40)); }
              return { scrolls: 400, wall_ms: Math.round(performance.now() - t0), frames, maxBlocksInDom: maxBlocks, maxDom, heapMB: performance.memory ? Math.round(performance.memory.usedJSHeapSize / 1048576) : null };
            }""")
            fr = flow.pop("frames")
            R["browser_scroll_long_sldc"] = {**flow, "frame_ms": summary(fr), "frames_over_50ms": sum(1 for f in fr if f > 50)}
            R["server_rss_mb"]["after_long_sldc"] = rss_mb(svc.proc.pid)
            srch = page.evaluate("""async () => { const r = await fetch(location.origin + '/api/status', { headers: { 'X-SLAI-Reader': '1' } }); return r.status; }""")
            page.screenshot(path=str(APP / "docs" / "screenshots" / "P2_long_sldc.png"))
            browser.close()
    finally:
        svc.stop()
        shutil.rmtree(tmp, ignore_errors=True)
    out = Path(args.out); out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(json.dumps(results, indent=2), encoding="utf-8")
    print(json.dumps(results, indent=2))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
